#!/usr/bin/env python3
"""Pack Minecraft's natural mob spawning data into src/js/02h_mcspawn_data.js.
usage: mcspawn_pack.py <data/minecraft dir of a 26.x data pack> <out.js>
Per biome: the gameplay/natural_mob_spawns attribute (spawns by category, spawn costs) and
gameplay/creature_world_gen_spawn_probability; structure spawn_overrides; the block and biome tags the
spawn rules read. Entries are [mob, weight, min, max]."""
import json, os, sys

D, out = sys.argv[1], sys.argv[2]
W = os.path.join(D, 'worldgen')
nm = lambda s: s.split(':', 1)[1] if ':' in s else s

def count(c):
    if isinstance(c, int): return c, c
    t = nm(c.get('type', 'constant'))
    if t == 'uniform': return c['min_inclusive'], c['max_inclusive']
    if t == 'constant': return c['value'], c['value']
    raise SystemExit('count provider ' + t)

def entries(L):
    return [[nm(e['type']), e.get('weight', 1), *count(e.get('count', 1))] for e in L]

biomes, costs, prob = {}, {}, {}
for f in sorted(os.listdir(os.path.join(W, 'biome'))):
    b = json.load(open(os.path.join(W, 'biome', f))); n = f[:-5]; a = b.get('attributes', {})
    s = a.get('minecraft:gameplay/natural_mob_spawns')
    if s:
        arg = s['argument']; biomes[n] = {c: entries(L) for c, L in arg.get('spawns_by_category', {}).items() if L}
        if arg.get('spawn_costs'): costs[n] = {nm(k): [v['energy_budget'], v['charge']] for k, v in arg['spawn_costs'].items()}
    p = a.get('minecraft:gameplay/creature_world_gen_spawn_probability')
    if p is not None: prob[n] = p

structs = {}
for f in sorted(os.listdir(os.path.join(W, 'structure'))):
    s = json.load(open(os.path.join(W, 'structure', f))).get('spawn_overrides')
    if s: structs[f[:-5]] = {c: [v['bounding_box'], entries(v['spawns'])] for c, v in s.items()}

def tags(kind, names):
    res = {}
    def get(t, seen=()):
        p = os.path.join(D, 'tags', kind, t + '.json')
        if not os.path.exists(p): return []
        o = []
        for v in json.load(open(p))['values']:
            v = v['id'] if isinstance(v, dict) else v
            o += get(nm(v[1:]), seen + (t,)) if v.startswith('#') else [nm(v)]
        return o
    for t in names: res[t] = sorted(set(get(t)))
    return res

btags = tags('block', [t[:-5] for t in os.listdir(os.path.join(D, 'tags', 'block')) if 'spawn' in t] + ['leaves', 'logs', 'sand', 'snow', 'terracotta', 'dirt'])
biotags = tags('worldgen/biome', ['allows_surface_slime_spawns', 'allows_tropical_fish_spawns_at_any_height', 'more_frequent_drowned_spawns', 'reduce_water_ambient_spawns', 'polar_bears_spawn_on_alternate_blocks'])
# dimension_type values (26.3): monster_spawn_block_light_limit, monster_spawn_light_level [min, max]
dims = {'overworld': [0, 0, 7], 'nether': [15, 7, 7], 'end': [0, 15, 15]}
data = {'biomes': biomes, 'costs': costs, 'prob': prob, 'structs': structs, 'btags': btags, 'biotags': biotags, 'dims': dims}
js = ('// Minecraft 26.3 natural mob spawning data (generated by tools/mcspawn_pack.py from the vanilla data pack)\n'
      'const MCS_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
open(out, 'w').write(js); print(len(js), 'bytes;', len(biomes), 'biomes;', len(structs), 'structures')
